import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import type { Plugin } from 'vite';

/** The import core's stylesheet uses for the deployment's theme. */
export const THEME_ALIAS = '@app-theme';

/**
 * Lets a deployment choose the theme every package is styled with.
 *
 * The deployment lists stylesheets under `recommand.theme` in its root
 * package.json, for example
 * `["@acme/brand/fonts.css", "@acme/brand/theme.css"]`. They are
 * imported, in that order, from a generated stylesheet that `@app-theme`
 * points to. Core imports `@app-theme` after its own defaults, so the theme
 * lands in the same Tailwind build and overrides them. Without a theme the
 * generated stylesheet is empty and core keeps its neutral defaults. Core's
 * THEMING.md lists the tokens a theme can set.
 */
export default function ThemePlugin(): Plugin {
  return {
    name: 'recommand-theme',

    async config(userConfig) {
      const deploymentRoot = resolve(process.cwd(), '../..');
      const stylesheets = await readThemeConfig(deploymentRoot);

      const generated = join(deploymentRoot, 'node_modules', '.recommand', 'theme.css');
      // Resolve from the deployment root to absolute paths, so aliases such as
      // `@recommand` (this framework) cannot capture a package specifier.
      const require = createRequire(join(deploymentRoot, 'package.json'));
      const body = stylesheets.length
        ? stylesheets
            .map((sheet) => `@import ${JSON.stringify(require.resolve(sheet))};`)
            .join('\n')
        : "/* No theme configured: core's neutral defaults apply. */";
      await mkdir(dirname(generated), { recursive: true });
      await writeFile(
        generated,
        `/* Generated by recommand-framework from recommand.theme. */\n${body}\n`,
      );

      return {
        resolve: {
          alias: {
            [THEME_ALIAS]: generated,
            ...userConfig.resolve?.alias,
          },
        },
      };
    },
  };
}

async function readThemeConfig(deploymentRoot: string): Promise<string[]> {
  try {
    const packageJson = JSON.parse(await readFile(join(deploymentRoot, 'package.json'), 'utf-8'));
    const theme = packageJson.recommand?.theme;
    if (theme === undefined) return [];
    if (Array.isArray(theme) && theme.every((sheet) => typeof sheet === 'string')) return theme;
    throw new Error('recommand.theme must be an array of stylesheet paths or package specifiers');
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') return [];
    throw error;
  }
}
